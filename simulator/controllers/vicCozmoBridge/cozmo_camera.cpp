Camera::Camera()
  : imageId_(0), lastChunk_(-1), encoding_(0), valid_(false),
    haveFrame_(false), frames_(0), drops_(0)
{
}

void Camera::OnPacket(const Packet& pkt)
{
  if (pkt.id != kEvtImageChunk || pkt.payload.size() < 20) {
    return;
  }

  Reader r(&pkt.payload[0], pkt.payload.size());
  r.Skip(4);
  const uint32_t imageId = r.U32();
  r.Skip(4);
  const int8_t encoding = r.I8();
  r.Skip(1);
  const uint8_t chunkCount = r.U8();
  const uint8_t chunkId = r.U8();
  r.Skip(2);
  const uint16_t len = r.U16();
  if (!r.Ok() || r.Remaining() < len) {
    return;
  }

  if (chunkId == 0) {
    partial_.clear();
    imageId_ = imageId;
    encoding_ = encoding;
    lastChunk_ = -1;
    valid_ = true;
  }

  if (!valid_ || imageId != imageId_ || (int)chunkId != lastChunk_ + 1) {
    if (valid_) {
      ++drops_;
    }
    valid_ = false;
    return;
  }

  partial_.insert(partial_.end(), r.Ptr(), r.Ptr() + len);
  lastChunk_ = chunkId;

  if (chunkId + 1 == chunkCount) {
    Complete();
    valid_ = false;
  }
}

void Camera::Complete()
{
  if (partial_.size() < 2 || encoding_ != kEncJpegMinimizedGray) {
    ++drops_;
    return;
  }

  const bool isColor = (partial_[0] != 0);
  const uint8_t* hdr = isColor ? kJpegHeaderColor : kJpegHeaderGray;
  const size_t hdrLen = isColor ? sizeof(kJpegHeaderColor) : sizeof(kJpegHeaderGray);
  const int jpegWidth = isColor ? (kCozmoCamWidth / 2) : kCozmoCamWidth;

  jpeg_.assign(hdr, hdr + hdrLen);
  jpeg_[kJpegHeightOff + 0] = (uint8_t)(kCozmoCamHeight >> 8);
  jpeg_[kJpegHeightOff + 1] = (uint8_t)(kCozmoCamHeight & 0xff);
  jpeg_[kJpegHeightOff + 2] = (uint8_t)(jpegWidth >> 8);
  jpeg_[kJpegHeightOff + 3] = (uint8_t)(jpegWidth & 0xff);

  size_t n = partial_.size();
  while (n > 1 && partial_[n - 1] == 0xff) {
    --n;
  }
  for (size_t i = 1; i < n; ++i) {
    jpeg_.push_back(partial_[i]);
    if (partial_[i] == 0xff) {
      jpeg_.push_back(0);
    }
  }
  jpeg_.push_back(0xff);
  jpeg_.push_back(0xd9);

  int w = 0, h = 0, comp = 0;
  const int want = isColor ? 3 : 1;
  stbi_uc* px = stbi_load_from_memory(&jpeg_[0], (int)jpeg_.size(), &w, &h, &comp, want);
  if (px == NULL) {
    ++drops_;
    return;
  }

  if (w == jpegWidth && h == kCozmoCamHeight) {
    rgb_.resize(kCozmoCamRGBBytes);
    for (int y = 0; y < kCozmoCamHeight; ++y) {
      const stbi_uc* src = px + (size_t)y * w * want;
      uint8_t* dst = &rgb_[(size_t)y * kCozmoCamWidth * 3];
      for (int x = 0; x < kCozmoCamWidth; ++x) {
        if (isColor) {
          const stbi_uc* s = src + (x / 2) * 3;
          dst[x * 3 + 0] = s[0];
          dst[x * 3 + 1] = s[1];
          dst[x * 3 + 2] = s[2];
        } else {
          const uint8_t v = src[x];
          dst[x * 3 + 0] = v;
          dst[x * 3 + 1] = v;
          dst[x * 3 + 2] = v;
        }
      }
    }
    haveFrame_ = true;
    ++frames_;
  } else {
    ++drops_;
  }
  stbi_image_free(px);
}

bool Camera::TakeFrame(uint8_t* rgb)
{
  if (!haveFrame_) {
    return false;
  }
  memcpy(rgb, &rgb_[0], kCozmoCamRGBBytes);
  haveFrame_ = false;
  return true;
}

